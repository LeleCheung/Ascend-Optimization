    for s in sizes[:d]:
        outer *= s
    inner = 1
    for s in sizes[d + 1 :]:
        inner *= s

    out_sizes = list(sizes)
    out_sizes[d] = max(N - 1, 0)
    output = torch.empty(out_sizes, dtype=y.dtype, device=y.device)

    if N <= 1 or outer * inner == 0:
        return output

    # dx/2 is folded into the increment so no second pass over the output runs.
    scale = dx * 0.5

    yc = y if y.is_contiguous() else y.contiguous()

    BLOCK = triton.next_power_of_2(max(N - 1, 1))

    if inner == 1:
        if BLOCK > 2048:
            # Wider tiles fit only for 2-byte elements inside the UB budget.
            c = 64 if y.element_size() <= 2 else 16
