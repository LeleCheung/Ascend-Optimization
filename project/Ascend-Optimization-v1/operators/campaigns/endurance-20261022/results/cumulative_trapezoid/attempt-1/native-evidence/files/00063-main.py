"""cumulative_trapezoid for Ascend 910B.

    out[..., i] = dx * sum_{j<=i} (y[..., j] + y[..., j+1]) / 2

On this target ``tl.cumsum`` costs a fixed ~0.45 ns per scanned element no
matter which tile shape it is given, which made the long-scan workloads ~6x
slower than the reference.  The prefix sum is therefore obtained from a Cube
matmul with the lower-triangular 0/1 matrix (``tl.dot``), which is ~10x
cheaper per element, and the chunk carry is a broadcast add plus one cheap row
reduction.  Short scans keep the exact vector cumsum; scans along a strided
axis block over the contiguous trailing axis so the vector lanes stay wide.
"""

import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

_MAX_L = 128
_SHORT = 32


@triton.jit
def _dot_scan_kernel(
    y_ptr,
    out_ptr,
    N: tl.constexpr,
    NOUT: tl.constexpr,
    ROWS: tl.constexpr,
    ROW_IN: tl.constexpr,
    SCAN_IN: tl.constexpr,
    BR: tl.constexpr,
    L: tl.constexpr,
    SCALE: tl.constexpr,
):
    pid = tl.program_id(0)
    r = pid * BR + tl.arange(0, BR)
    c = tl.arange(0, L)
    rm = r < ROWS
    seg = (c[:, None] >= c[None, :]).to(y_ptr.dtype.element_ty)
    carry = tl.zeros((BR,), dtype=tl.float32)
    in_base = r[:, None] * ROW_IN
    out_base = r[:, None] * NOUT
    for cc in range(0, (NOUT + L - 1) // L):
        kk = cc * L + c
        m = (kk < NOUT)[None, :] & rm[:, None]
        a = tl.load(y_ptr + in_base + kk[None, :] * SCAN_IN, mask=m, other=0.0)
        b = tl.load(y_ptr + in_base + (kk + 1)[None, :] * SCAN_IN, mask=m, other=0.0)
        t = ((a + b) * SCALE).to(y_ptr.dtype.element_ty)
        local = tl.dot(t, seg).to(tl.float32)
        tl.store(out_ptr + out_base + kk[None, :], local + carry[:, None], mask=m)
        carry += tl.sum(tl.where(c[None, :] == (L - 1), local, 0.0), axis=1)


@triton.jit
def _vec_scan_kernel(
    y_ptr,
    out_ptr,
    N: tl.constexpr,
    NOUT: tl.constexpr,
    ROWS: tl.constexpr,
    ROW_IN: tl.constexpr,
    SCAN_IN: tl.constexpr,
    BR: tl.constexpr,
    BLOCK: tl.constexpr,
    SCALE: tl.constexpr,
):
    pid = tl.program_id(0)
    r = pid * BR + tl.arange(0, BR)
    k = tl.arange(0, BLOCK)
    m = (k < NOUT)[None, :] & (r < ROWS)[:, None]
    in_base = r[:, None] * ROW_IN
    a = tl.load(y_ptr + in_base + k[None, :] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
    b = tl.load(y_ptr + in_base + (k + 1)[None, :] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
    cs = tl.cumsum((a + b) * SCALE, axis=1)
    tl.store(out_ptr + r[:, None] * NOUT + k[None, :], cs, mask=m)


@triton.jit
def _col_scan_kernel(
    y_ptr,
    out_ptr,
    NOUT: tl.constexpr,
    INNER: tl.constexpr,
    NBLK: tl.constexpr,
    ROW_IN: tl.constexpr,
    SCAN_IN: tl.constexpr,
    IN_IN: tl.constexpr,
    BI: tl.constexpr,
    L: tl.constexpr,
    SCALE: tl.constexpr,
):
    pid = tl.program_id(0)
    o = pid // NBLK
    i = (pid % NBLK) * BI + tl.arange(0, BI)
    im = i < INNER
    k = tl.arange(0, L)
    carry = tl.zeros((BI,), dtype=tl.float32)
    in_base = o * ROW_IN + i[None, :] * IN_IN
    out_base = o * (NOUT * INNER) + i[None, :]
    for cc in range(0, (NOUT + L - 1) // L):
        kk = cc * L + k
        m = (kk < NOUT)[:, None] & im[None, :]
        a = tl.load(y_ptr + in_base + kk[:, None] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
        b = tl.load(y_ptr + in_base + (kk + 1)[:, None] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
        local = tl.cumsum((a + b) * SCALE, axis=0)
        tl.store(out_ptr + out_base + kk[:, None] * INNER, local + carry[None, :], mask=m)
        carry += tl.sum(tl.where(k[:, None] == (L - 1), local, 0.0), axis=0)


def _plan(ndim, d, sizes, strides):
    """(outer, N, inner, row_in, scan_in, in_in) or None if layout is hostile."""
    N = sizes[d]
    outer = 1
    for s in sizes[:d]:
        outer *= s
    inner = 1
    for s in sizes[d + 1:]:
        inner *= s

    row_in = 0
    if outer > 1:
        for k in range(d - 1):
            if strides[k] != strides[k + 1] * sizes[k + 1]:
                return None
        row_in = strides[d - 1]

    in_in = 1
    if inner > 1:
        for k in range(d + 1, ndim - 1):
            if strides[k] != strides[k + 1] * sizes[k + 1]:
                return None
        if d + 1 == ndim - 1 and strides[ndim - 1] != 1:
            in_in = strides[ndim - 1]
    return outer, N, inner, row_in, strides[d], in_in


def _rows_tile(n_out, outer):
    L = _MAX_L if n_out > _MAX_L else max(triton.next_power_of_2(n_out), 16)
    br = 32 if outer % 32 == 0 else 16
    return br, L


def _cols_tile(n_out, inner):
    bi = 64 if inner >= 64 else max(triton.next_power_of_2(inner), 16)
    L = _MAX_L if n_out > _MAX_L else max(triton.next_power_of_2(n_out), 16)
    while L * bi > 8192:
        L //= 2
    return bi, max(L, 16)


def run(y, *, dx=1, dim=-1):
    logger.debug("GEMS CUMULATIVE_TRAPEZOID")

    ndim = y.dim()
    if ndim == 0:
        raise IndexError(
            "cumulative_trapezoid: input tensor must have at least one dimension")
    d = dim if dim >= 0 else dim + ndim
    if d < 0 or d >= ndim:
        raise IndexError("cumulative_trapezoid: dim out of range")

    sizes = list(y.shape)
    strides = list(y.stride())
    N = sizes[d]
    n_out = N - 1

    out_sizes = list(sizes)
    out_sizes[d] = max(n_out, 0)
    output = torch.empty(out_sizes, dtype=y.dtype, device=y.device)
    if n_out == 0:
        return output

    if isinstance(dx, torch.Tensor):
        dx = float(dx)
    scale = 0.5 * float(dx)

    plan = _plan(ndim, d, sizes, strides)
    if plan is None:
        y = y.contiguous()
        strides = list(y.stride())
        plan = _plan(ndim, d, sizes, strides)
    outer, N, inner, row_in, scan_in, in_in = plan

    if inner == 1:
        if n_out <= _SHORT:
            br = 16 if outer >= 16 else 1
            _vec_scan_kernel[(triton.cdiv(outer, br),)](
                y, output,
                N=N, NOUT=n_out, ROWS=outer, ROW_IN=row_in, SCAN_IN=scan_in,
                BR=br, BLOCK=max(triton.next_power_of_2(n_out), 16), SCALE=scale,
            )
        else:
            br, L = _rows_tile(n_out, outer)
            _dot_scan_kernel[(triton.cdiv(outer, br),)](
                y, output,
                N=N, NOUT=n_out, ROWS=outer, ROW_IN=row_in, SCAN_IN=scan_in,
                BR=br, L=L, SCALE=scale,
            )
    else:
        bi, L = _cols_tile(n_out, inner)
        nblk = triton.cdiv(inner, bi)
        _col_scan_kernel[(outer * nblk,)](
            y, output,
            NOUT=n_out, INNER=inner, NBLK=nblk, ROW_IN=row_in,
            SCAN_IN=scan_in, IN_IN=in_in, BI=bi, L=L, SCALE=scale,
        )
    return output
