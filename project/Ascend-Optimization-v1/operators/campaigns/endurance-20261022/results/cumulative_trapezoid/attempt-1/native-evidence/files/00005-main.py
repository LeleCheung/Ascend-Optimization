_PLANS = {}


def run(y, *, dx=1, dim=-1):
    if type(dx) is not float and type(dx) is not int:
        dx = float(dx)

    key = (y.dtype, y.shape, y.stride(), y.dim(), dim, dx)
    plan = _PLANS.get(key)
    if plan is None:
        b = _build(list(y.shape), list(y.stride()), y.dim(), dim, dx)
        plan = [b[0], None, b[1], b[2], b[3], b[4], b[5], False]
        _PLANS[key] = plan

    if plan[5]:
        y = y.contiguous()
    output = y.new_empty(plan[0])
    launch = plan[2]
    if launch is not None:
        ck = plan[1]
        if ck is not None:
            _fire(ck, plan[3], plan[4], y, output)
        else:
            launch(plan[3], y, output, *plan[4])
            if not plan[7]:
                plan[7] = True
                ck = None
                try:
                    ck = _prebuild(plan[6], plan[3], plan[4], y, output)
                    if ck is not None:
                        _fire(ck, plan[3], plan[4], y, output)
                except Exception:
                    ck = None
                plan[1] = ck
    return output
