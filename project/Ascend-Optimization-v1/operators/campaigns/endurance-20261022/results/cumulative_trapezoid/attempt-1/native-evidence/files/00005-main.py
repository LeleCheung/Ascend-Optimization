def _prebuild(jit_fn, grid, args, y, out):
    """Compile once and hand back the raw launcher.

    The full JIT dispatch costs ~60 us per call on this backend (measured),
    while the bound C launcher with a pre-read stream costs ~19 us, and that
    gap is the whole cost of the small workloads.  Returns None if this
    Triton build cannot be driven that way, in which case the caller keeps
    using the ordinary ``kernel[grid](...)`` path.
    """
    ck = jit_fn.warmup(y, out, *args, grid=grid)
    if ck is None:
        return None
    ck._init_handles()
    return ck


def _fire(ck, grid, args, y, out):
    stream = _driver.active.get_current_stream(_driver.active.get_current_device())
    ck.run(grid[0], 1, 1, stream, ck.function, ck.packed_metadata,
           None, None, None, y, out, *args)


def _layout(ndim, d, sizes, strides):
    """(outer, N, inner, row_in, scan_in, in_in) or None if layout is hostile."""
    N = sizes[d]
    outer = 1
    for s in sizes[:d]:
        outer *= s
    inner = 1
    for s in sizes[d + 1:]:
        inner *= s

    row_in = 0
    if outer > 1:
        for k in range(d - 1):
            if strides[k] != strides[k + 1] * sizes[k + 1]:
                return None
        row_in = strides[d - 1]

    in_in = 1
    if inner > 1:
        for k in range(d + 1, ndim - 1):
            if strides[k] != strides[k + 1] * sizes[k + 1]:
                return None
        if d + 1 == ndim - 1 and strides[ndim - 1] != 1:
            in_in = strides[ndim - 1]
    return outer, N, inner, row_in, strides[d], in_in


def _build(sizes, strides, ndim, dim, dx):
    """Everything the launch needs, computed once per layout key."""
    d = dim if dim >= 0 else dim + ndim
    if d < 0 or d >= ndim:
        raise IndexError("cumulative_trapezoid: dim out of range")

    N = sizes[d]
    n_out = N - 1
    out_sizes = list(sizes)
    out_sizes[d] = max(n_out, 0)
    if n_out == 0:
        return out_sizes, None, None, None, False, None

    scale = 0.5 * float(dx)
    lay = _layout(ndim, d, sizes, strides)
    need_copy = lay is None
    if need_copy:
        sizes = list(sizes)
        c = 1
        strides = [0] * ndim
        for k in range(ndim - 1, -1, -1):
            strides[k] = c
            c *= sizes[k]
        lay = _layout(ndim, d, sizes, strides)
    outer, N, inner, row_in, scan_in, in_in = lay

    if inner > 1:
        bi = 64 if inner >= 64 else max(triton.next_power_of_2(inner), 16)
        L = _VEC_L if n_out > _VEC_L else max(triton.next_power_of_2(n_out), 16)
        while L * bi > 8192:
            L //= 2
        L = max(L, 16)
        nblk = triton.cdiv(inner, bi)
        launch = _launch_col
        jit_fn = _col_scan_kernel
        grid = (outer * nblk,)
        args = (n_out, inner, nblk, row_in, scan_in, in_in, bi, L, scale)
    elif (scan_in == 1 and n_out > _SHORT and outer % 16 == 0
            and outer * n_out >= _DOT_MIN_ELEMS):
        br = _DOT_BR if outer % _DOT_BR == 0 else 16
        launch = _launch_dot
        jit_fn = _dot_scan_kernel
        grid = (outer // br,)
        args = (n_out, row_in, scan_in, br, _DOT_L, scale)
    else:
        br = 4 if (outer >= 4 and n_out <= 1024) else 1
        L = _VEC_L if n_out > _VEC_L else max(triton.next_power_of_2(n_out), 16)
        launch = _launch_vec
        jit_fn = _vec_scan_kernel
        grid = (triton.cdiv(outer, br),)
        args = (n_out, outer, row_in, scan_in, br, L, scale)
    return out_sizes, launch, grid, args, need_copy, jit_fn


