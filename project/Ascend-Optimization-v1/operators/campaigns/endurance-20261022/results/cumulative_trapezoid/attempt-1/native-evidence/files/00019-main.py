"""cumulative_trapezoid for Ascend 910B.

    out[..., i] = dx * sum_{j<=i} (y[..., j] + y[..., j+1]) / 2

Measured on this target, ``tl.cumsum`` costs a fixed ~0.45 ns per scanned
element for every tile shape tried (a 1024x4096 scan takes 1.70 ms with
BR x L in {1,2,4,8,16} x {256,512,1024,4096}), while copy and ``tl.sum`` stay
at the launch floor.  Long scans therefore take their prefix sum from a Cube
matmul with the 0/1 lower-triangular matrix (``tl.dot``), ~10x cheaper per
element, with the inter-chunk carry carried as a broadcast tile.  Short scans
keep the exact vector cumsum, and scans along a strided axis block over the
contiguous trailing axis so the vector lanes stay wide.
"""

import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

_DOT_MIN_ELEMS = 262144
_DOT_BR = 32
_DOT_L = 128
_VEC_L = 1024


@triton.jit
def _dot_scan_kernel(
    y_ptr,
    out_ptr,
    NOUT: tl.constexpr,
    ROW_IN: tl.constexpr,
    SCAN_IN: tl.constexpr,
    BR: tl.constexpr,
    L: tl.constexpr,
    SCALE,
):
    pid = tl.program_id(0)
    r = pid * BR + tl.arange(0, BR)
    c = tl.arange(0, L)
    # seg[k, i] = 1 for k <= i, hence dot(t, seg)[m, i] == sum_{k <= i} t[m, k]
    seg = (c[None, :] >= c[:, None]).to(y_ptr.dtype.element_ty)
    carry = tl.zeros((BR, L), dtype=tl.float32)
    in_base = r[:, None] * ROW_IN
    for cc in range(0, (NOUT + L - 1) // L):
        kk = cc * L + c
        m = (kk < NOUT)[None, :]
        a = tl.load(y_ptr + in_base + kk[None, :] * SCAN_IN, mask=m, other=0.0)
        b = tl.load(y_ptr + in_base + (kk + 1)[None, :] * SCAN_IN, mask=m, other=0.0)
        t = ((a + b) * SCALE).to(y_ptr.dtype.element_ty)
        lp = tl.dot(t, seg).to(tl.float32) + carry
        tl.store(out_ptr + r[:, None] * NOUT + kk[None, :], lp, mask=m)
        last = tl.sum(tl.where(c[None, :] == (L - 1), lp, 0.0), axis=1)
        carry = last[:, None] + tl.zeros((BR, L), dtype=tl.float32)


@triton.jit
def _vec_scan_kernel(
    y_ptr,
    out_ptr,
    NOUT: tl.constexpr,
    ROWS: tl.constexpr,
    ROW_IN: tl.constexpr,
    SCAN_IN: tl.constexpr,
    BR: tl.constexpr,
    L: tl.constexpr,
    SCALE: tl.constexpr,
):
    pid = tl.program_id(0)
    r = pid * BR + tl.arange(0, BR)
    c = tl.arange(0, L)
    carry = tl.zeros((BR,), dtype=tl.float32)
    in_base = r[:, None] * ROW_IN
    for cc in range(0, (NOUT + L - 1) // L):
        kk = cc * L + c
        m = (kk < NOUT)[None, :] & (r < ROWS)[:, None]
        a = tl.load(y_ptr + in_base + kk[None, :] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
        b = tl.load(y_ptr + in_base + (kk + 1)[None, :] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
        cs = tl.cumsum((a + b) * SCALE, axis=1) + carry[:, None]
        tl.store(out_ptr + r[:, None] * NOUT + kk[None, :], cs, mask=m)
        carry = tl.sum(tl.where(c[None, :] == (L - 1), cs, 0.0), axis=1)


@triton.jit
def _col_scan_kernel(
    y_ptr,
    out_ptr,
    NOUT: tl.constexpr,
    INNER: tl.constexpr,
    NBLK: tl.constexpr,
    ROW_IN: tl.constexpr,
    SCAN_IN: tl.constexpr,
    IN_IN: tl.constexpr,
    BI: tl.constexpr,
    L: tl.constexpr,
    SCALE: tl.constexpr,
):
    pid = tl.program_id(0)
    o = pid // NBLK
    i = (pid % NBLK) * BI + tl.arange(0, BI)
    im = i < INNER
    k = tl.arange(0, L)
    carry = tl.zeros((BI,), dtype=tl.float32)
    in_base = o * ROW_IN + i[None, :] * IN_IN
    out_base = o * (NOUT * INNER) + i[None, :]
    for cc in range(0, (NOUT + L - 1) // L):
        kk = cc * L + k
        m = (kk < NOUT)[:, None] & im[None, :]
        a = tl.load(y_ptr + in_base + kk[:, None] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
        b = tl.load(y_ptr + in_base + (kk + 1)[:, None] * SCAN_IN, mask=m, other=0.0).to(tl.float32)
        cs = tl.cumsum((a + b) * SCALE, axis=0) + carry[None, :]
        tl.store(out_ptr + out_base + kk[:, None] * INNER, cs, mask=m)
        carry = tl.sum(tl.where(k[:, None] == (L - 1), cs, 0.0), axis=0)


def _plan(ndim, d, sizes, strides):
    """(outer, N, inner, row_in, scan_in, in_in) or None if layout is hostile."""
    N = sizes[d]
    outer = 1
    for s in sizes[:d]:
        outer *= s
    inner = 1
    for s in sizes[d + 1:]:
        inner *= s

    row_in = 0
    if outer > 1:
        for k in range(d - 1):
            if strides[k] != strides[k + 1] * sizes[k + 1]:
                return None
        row_in = strides[d - 1]

    in_in = 1
    if inner > 1:
        for k in range(d + 1, ndim - 1):
            if strides[k] != strides[k + 1] * sizes[k + 1]:
                return None
        if d + 1 == ndim - 1 and strides[ndim - 1] != 1:
            in_in = strides[ndim - 1]
    return outer, N, inner, row_in, strides[d], in_in


def run(y, *, dx=1, dim=-1):
    logger.debug("GEMS CUMULATIVE_TRAPEZOID")

    ndim = y.dim()
    if ndim == 0:
        raise IndexError(
            "cumulative_trapezoid: input tensor must have at least one dimension")
    d = dim if dim >= 0 else dim + ndim
    if d < 0 or d >= ndim:
        raise IndexError("cumulative_trapezoid: dim out of range")

    sizes = list(y.shape)
    strides = list(y.stride())
    N = sizes[d]
    n_out = N - 1

    out_sizes = list(sizes)
    out_sizes[d] = max(n_out, 0)
    output = torch.empty(out_sizes, dtype=y.dtype, device=y.device)
    if n_out == 0:
        return output

    if isinstance(dx, torch.Tensor):
        dx = float(dx)
    scale = 0.5 * float(dx)

    plan = _plan(ndim, d, sizes, strides)
    if plan is None:
        y = y.contiguous()
        strides = list(y.stride())
        plan = _plan(ndim, d, sizes, strides)
    outer, N, inner, row_in, scan_in, in_in = plan

    if inner > 1:
        bi = 64 if inner >= 64 else max(triton.next_power_of_2(inner), 16)
        L = _VEC_L if n_out > _VEC_L else max(triton.next_power_of_2(n_out), 16)
        while L * bi > 8192:
            L //= 2
        L = max(L, 16)
        nblk = triton.cdiv(inner, bi)
        _col_scan_kernel[(outer * nblk,)](
            y, output,
            NOUT=n_out, INNER=inner, NBLK=nblk, ROW_IN=row_in,
            SCAN_IN=scan_in, IN_IN=in_in, BI=bi, L=L, SCALE=scale,
        )
    elif (scan_in == 1 and n_out > 32 and outer % 16 == 0
            and outer * n_out >= _DOT_MIN_ELEMS):
        br = _DOT_BR if outer % _DOT_BR == 0 else 16
        _dot_scan_kernel[(outer // br,)](
            y, output,
            NOUT=n_out, ROW_IN=row_in, SCAN_IN=scan_in, BR=br, L=_DOT_L,
            SCALE=scale,
        )
    else:
        br = 4 if (outer >= 4 and n_out <= 1024) else 1
        L = _VEC_L if n_out > _VEC_L else max(triton.next_power_of_2(n_out), 16)
        _vec_scan_kernel[(triton.cdiv(outer, br),)](
            y, output,
            NOUT=n_out, ROWS=outer, ROW_IN=row_in, SCAN_IN=scan_in,
            BR=br, L=L, SCALE=scale,
        )
    return output
