@triton.jit
def _gn_kernel(
    X,
    OUT,
    MEAN,
    RSTD,
    W,
    B,
    eps,
    HW: tl.constexpr,
    CG: tl.constexpr,
    G: tl.constexpr,
    NS: tl.constexpr,
    CS: tl.constexpr,
    SS: tl.constexpr,
    COUNT: tl.constexpr,
    BLOCK: tl.constexpr,
    HAS_AFFINE: tl.constexpr,
    EVEN: tl.constexpr,
):
    g = tl.program_id(0)
    n = tl.program_id(1)
    c0 = g * CG
    xb = X + n * NS + c0 * CS
    idx = tl.arange(0, BLOCK)

    accs = tl.zeros([BLOCK], dtype=tl.float32)
    accq = tl.zeros([BLOCK], dtype=tl.float32)
    for ci in range(0, CG):
        co = ci * CS
        for start in range(0, HW, BLOCK):
            hi = start + idx
            if EVEN:
                xf = tl.load(xb + co + hi * SS).to(tl.float32)
            else:
                msk = hi < HW
                xf = tl.load(xb + co + hi * SS, mask=msk, other=0.0).to(tl.float32)
            accs += xf
            accq += xf * xf

    inv = 1.0 / COUNT
    mean = tl.sum(accs, 0) * inv
    var = tl.sum(accq, 0) * inv - mean * mean
    rstd = 1.0 / tl.sqrt(var + eps)

    midx = n * G + g
    tl.store(MEAN + midx, mean.to(MEAN.dtype.element_ty))
    tl.store(RSTD + midx, rstd.to(RSTD.dtype.element_ty))

    # OUT is allocated contiguous as (N, C, HW): group (n, g) covers
    # [midx * COUNT, (midx + 1) * COUNT) and element (ci, hw) sits at
    # ci * HW + hw.  The input side keeps its own strides.
    cb = midx * COUNT
    for ci in range(0, CG):
        co = ci * CS
        oo = ci * HW
        if HAS_AFFINE:
            a = rstd * tl.load(W + c0 + ci).to(tl.float32)
            b2 = tl.load(B + c0 + ci).to(tl.float32) - mean * a
        else:
            a = rstd
            b2 = -mean * rstd
        for start in range(0, HW, BLOCK):
            hi = start + idx
            if EVEN:
                xf = tl.load(xb + co + hi * SS).to(tl.float32)
                tl.store(OUT + cb + oo + hi, (xf * a + b2).to(OUT.dtype.element_ty))
            else:
                msk = hi < HW
                xf = tl.load(xb + co + hi * SS, mask=msk, other=0.0).to(tl.float32)
                tl.store(
                    OUT + cb + oo + hi,
                    (xf * a + b2).to(OUT.dtype.element_ty),
                    mask=msk,
                )


