def _resolve_stream():
    """Cache a cheap callable returning this device's current stream handle.

    Only a candidate reproducing the full ``current_stream()`` handle is
    accepted, so the fast path can never pick a different stream than the one
    the caller is using.
    """
    global _STREAM_FN
    if _STREAM_FN is not None:
        return _STREAM_FN
    good = None
    try:
        good = _stream_slow()
    except Exception:
        return _stream_slow
    for cand in _stream_candidates():
        try:
            if cand() == good:
                _STREAM_FN = cand
                return cand
        except Exception:
            continue
    return _stream_slow


def _pick_block(hw):
    blk = _BLOCK_CACHE.get(hw)
    if blk is None:
        blk = 64
        while blk < hw and blk < 4096:
            blk <<= 1
        _BLOCK_CACHE[hw] = blk
    return blk


