"""Native group normalization as a single fused Triton kernel.

One program per (group, batch) pair.  Each program

1. walks its whole group (CG channels x HW elements) accumulating sum and
   sum-of-squares in fp32 with a chunked per-channel loop,
2. derives ``mean`` / ``rstd`` and stores them,
3. re-walks the same range applying ``y = x * a + b`` with per-channel
   ``a = rstd * w`` and ``b = bias - mean * rstd * w``.

The operator is measured with walltime, and on this target the device work
(~6.5us for the representative shape) is far smaller than the reference
operator's ~33us/call, so the score is decided by host-side cost per call.  A
bounded diagnostic on the target decomposed that cost as

    raw compiled-kernel launch  ~23.3us
    two ``torch.empty`` allocs  ~13.7us
    two ``buf[i]`` selects       ~6.0us
    wrapper glue (key, ptrs)    ~10.8us
    (plain Triton JIT dispatch  ~77.5us, i.e. unusable per call)

so this wrapper keeps one cached dictionary lookup keyed on shape/stride/dtype
metadata, allocates the two outputs with ``new_empty`` (no dtype/device kwarg
parsing), splits them with a single ``unbind``, and launches through the
compiled kernel's own ``run.launch`` entry with every shape/stride constant
already bound, so no per-call specialization hashing or pointer extraction
happens in Python.
"""
import torch
