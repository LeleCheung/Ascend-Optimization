def _build(key, x, shp, strd, weight, bias, N, C, HxW, group, eps):
    dim = x.dim()
    ns = strd[0]
    cs = strd[1]
    ss = 1
    copy = False
    xk = x
    if dim > 2:
        ss = strd[dim - 1]
        if dim > 3:
            acc = 1
            for d in range(dim - 1, 2, -1):
                if strd[d] != ss * acc:
                    copy = True
                    break
                acc *= shp[d]
    if copy:
        xk = x.contiguous()
        st2 = xk.stride()
        ns = st2[0]
        cs = st2[1]
        ss = st2[dim - 1]

    hw = HxW
    cg = C // group
    count = cg * hw
    ng = N * group
    block = _pick_block(hw)
    even = hw % block == 0
    has_affine = weight is not None and bias is not None
    wsrc = xk if weight is None else weight
    bsrc = xk if bias is None else bias

    out = x.new_empty(shp)
    buf = x.new_empty((2, N, group))
    mean, rstd = buf.unbind(0)

    launcher = None
    try:
        gen = _gen_kernel(hw, cg, group, ns, cs, ss, count, ng, block, even,
                          has_affine, eps)
        if has_affine:
            gen[(group, N)](xk, out, buf, wsrc, bsrc)
        else:
            gen[(group, N)](xk, out, buf)
        caches = gen.device_caches
        ck = None
        if caches:
            cache = caches[list(caches.keys())[0]][0]
            if cache:
                ck = list(cache.values())[0]
        if ck is not None:
            gargs = (xk, out, buf, wsrc, bsrc) if has_affine else (xk, out, buf)
            launcher = _tune_launch(ck, (group, N, 1), gargs, _resolve_stream(),
                                    has_affine)
    except Exception:
        launcher = None

    if launcher is None:
        before = _cache_keys()
        _gn_kernel[(group, N)](
            xk,
            out,
            mean,
            rstd,
            wsrc,
            bsrc,
            eps,
            HW=hw,
            CG=cg,
            G=group,
            NS=ns,
            CS=cs,
            SS=ss,
            COUNT=count,
            BLOCK=block,
            HAS_AFFINE=has_affine,
            EVEN=even,
        )
        ck = _find_new(before)
        if ck is not None and hasattr(ck, "run") and hasattr(ck.run, "launch"):
            try:
                launcher = _general_launch(ck, hw, cg, group, N, ns, cs, ss, count,
                                           block, has_affine, even, eps,
                                           _resolve_stream())
            except Exception:
                launcher = None
        if launcher is None:
            launcher = _plain_launch(hw, cg, group, ns, cs, ss, count, block,
                                     has_affine, even, eps, N)

    _CACHE[key] = (launcher, shp, (2, N, group), copy)
    return out, mean, rstd


def run(input, weight, bias, N, C, HxW, group, eps):
    x = input
    shp = x.shape
    key = (
        x.dtype,
        shp,
        x.stride(),
        N,
        C,
        group,
        eps,
        None if weight is None else weight.dtype,
        None if bias is None else bias.dtype,
    )
    e = _CACHE.get(key)
    if e is None:
        return _build(key, x, shp, x.stride(), weight, bias, N, C, HxW, group, eps)

    out = x.new_empty(e[1])
    buf = x.new_empty(e[2])
    mean, rstd = buf.unbind(0)
    if e[3]:
        x = x.contiguous()
    e[0](x, out, buf, weight, bias)
    return out, mean, rstd


