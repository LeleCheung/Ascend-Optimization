"""Native group normalization as a single fused Triton kernel.

One program per (group, batch) pair: it accumulates sum / sum-of-squares over
the whole group (CG channels x HW elements) in fp32, derives ``mean``/``rstd``
into one packed ``(2, N, group)`` buffer, and re-walks the same range applying
``y = x * a + b`` with per-channel ``a = rstd * w``, ``b = bias - mean * a``.

The score is measured with walltime and on this target the kernel itself is
~6.5us, far below the reference operator's ~33us/call, so per-call host cost
decides the result.  Bounded A/B diagnostics on the target showed that this
runtime's compiled-kernel launch path costs ~39us even for a no-op kernel and
that every extra launch argument adds ~1.1us.  The wrapper therefore

* generates, once per (geometry, dtype, group, eps, affine) specialization, a
  Triton kernel whose HW/CG/strides/BLOCK/COUNT/eps are *literals*, leaving
  only 5 tensor arguments (X, OUT, BUF, W, B) - 26 launch slots become 14, and
  mean/rstd share one pointer through a packed buffer,
* allocates both outputs with ``new_empty`` and splits them with one
  ``unbind``,
* and launches through whichever compiled entry (``run`` or ``run.launch``)
  the target reports as cheapest, measured once at build time with the real
  arguments, with every constant pre-bound.
"""
