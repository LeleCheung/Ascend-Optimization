def _tune_launch(ck, grid, args, sget, affine):
    """Pick the cheapest compiled launch entry for this specialization.

    One-time host-side dispatch choice over the entries this runtime exposes;
    it re-launches the very same arguments, so nothing about the result
    changes.
    """
    gx, gy, gz = grid
    fnp = getattr(ck, "function", None)
    pm = getattr(ck, "packed_metadata", None)
    if fnp is None or pm is None:
        return None
    calls = []
    runner = getattr(ck, "run", None)
    if runner is not None:
        calls.append(runner)
        inner = getattr(runner, "launch", None)
        if inner is not None:
            calls.append(inner)
    best = None
    for call in calls:
        try:
            for _ in range(4):
                call(gx, gy, gz, sget(), fnp, pm, None, None, None, *args)
            torch.npu.synchronize()
            t0 = time.perf_counter()
            for _ in range(16):
                call(gx, gy, gz, sget(), fnp, pm, None, None, None, *args)
            torch.npu.synchronize()
            dt = time.perf_counter() - t0
        except Exception:
            continue
        if best is None or dt < best[0]:
            best = (dt, call)
    if best is None:
        return None
    call = best[1]

    if affine:

        def launch(xin, out, buf, w, b, _c=call):
            _c(gx, gy, gz, sget(), fnp, pm, None, None, None, xin, out, buf, w, b)

    else:

        def launch(xin, out, buf, w, b, _c=call):
            _c(gx, gy, gz, sget(), fnp, pm, None, None, None, xin, out, buf)

    return launch


