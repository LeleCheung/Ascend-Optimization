"""Native group normalization as a single fused Triton kernel.

One program per (group, batch) pair.  Each program

1. walks its whole group (CG channels x HW elements) accumulating sum and
   sum-of-squares in fp32 with a chunked per-channel loop,
2. derives ``mean`` / ``rstd`` and stores them,
3. re-walks the same range applying ``y = x * a + b`` with per-channel
   ``a = rstd * w`` and ``b = bias - mean * rstd * w``.

Measured on this target, the whole operator is host-overhead bound (the
reference operator itself measures ~30us/call for every shape), so the wrapper
launch one kernel, does one output allocation plus one fused mean/rstd
allocation, and re-uses the compiled kernel's own launch entry once Triton has
built it for the current specialization.
"""
