def _pow2_at_most(x: int, cap: int) -> int:
    b = 1
    while b * 2 <= x and b * 2 <= cap:
        b *= 2
    return b


def run(grad, dim, indices, sizes, keepdim):
    shape = [int(s) for s in sizes]
    ndim = len(shape)
    d = int(dim)
    if d < 0:
        d += ndim

    outer = 1
    for s in shape[:d]:
        outer *= s
    red = shape[d]
    inner = 1
    for s in shape[d + 1:]:
        inner *= s

    out = torch.empty(shape, dtype=grad.dtype, device=grad.device)

    # Flat-element addressing of grad / indices.  A keepdim singleton on the
    # reduced axis does not change flat order, so the same formula is used.
    g_s1 = grad.stride(-1) if grad.dim() > 0 else 0
    i_s1 = indices.stride(-1) if indices.dim() > 0 else 0
    g_s0 = g_s1 * inner
    i_s0 = i_s1 * inner

    if inner == 1 and red <= 8192:
        # One program owns ROWS consecutive (contiguous) output rows: fewer,
        # larger programs amortize the flat per-program cost measured on the
        # target, and the store covers a contiguous ROWS*red element block.
        COLS = _pow2_at_most(red, 8192)
        TILE = 8192
        rows_cap = 64
        ROWS = _pow2_at_most(max(TILE // red, 1), rows_cap)
        if ROWS > outer:
            ROWS = _pow2_at_most(outer, rows_cap)
        nblk = (outer + ROWS - 1) // ROWS
        MASKED = (COLS != red) or (outer % ROWS != 0)
        _vsrb_lastdim_kernel[(nblk,)](
            grad,
            indices,
            out,
            outer,
            red,
            g_s0,
            i_s0,
            ROWS=ROWS,
            COLS=COLS,
            MASKED=MASKED,
        )
    else:
        IB = _pow2_at_most(inner, 1024)
        nblk = (inner + IB - 1) // IB
        _vsrb_general_kernel[(outer, nblk)](
            grad, indices, out, red, inner, g_s0, g_s1, i_s0, i_s1, IB=IB
        )
    return out


