@triton.jit
def _fused_lastdim(
    g_ptr,
    idx_ptr,
    out_ptr,
    M,
    R: tl.constexpr,
    K: tl.constexpr,
    BK: tl.constexpr,
    EVEN: tl.constexpr,
    FULLK: tl.constexpr,
):
    """out[row, col] = grad[row] if indices[row] == col else 0."""
    pid_m = tl.program_id(0)
    pid_k = tl.program_id(1)
    rows = pid_m * R + tl.arange(0, R)
    cols = pid_k * BK + tl.arange(0, BK)

    if EVEN:
        g = tl.load(g_ptr + rows)
        idx = tl.load(idx_ptr + rows).to(tl.int32)
    else:
        rmask = rows < M
        g = tl.load(g_ptr + rows, mask=rmask, other=0)
        idx = tl.load(idx_ptr + rows, mask=rmask, other=0).to(tl.int32)

    vals = tl.where(cols[None, :] == idx[:, None], g[:, None], tl.zeros_like(g)[:, None])
    offs = rows[:, None] * K + cols[None, :]

    if FULLK:
        if EVEN:
            tl.store(out_ptr + offs, vals)
        else:
            tl.store(out_ptr + offs, vals, mask=rmask[:, None])
    else:
        if EVEN:
            tl.store(out_ptr + offs, vals, mask=cols[None, :] < K)
        else:
            tl.store(
                out_ptr + offs,
                vals,
                mask=rmask[:, None] & (cols[None, :] < K),
            )


