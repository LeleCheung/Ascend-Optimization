_ZERO_BLOCK = 4096
_SCATTER_BLOCK = 1024
_TARGET_BYTES = 32768
_MAX_BK = 8192


def _group(shape, stride):
    """Collapse a logical (shape, stride) group into <= 2 affine levels.

    Flat index t in [0, prod(shape)) maps to memory offset
        (t // SPLIT) * ST0 + (t % SPLIT) * ST1
    """
    dims = [(s, st) for s, st in zip(shape, stride) if s != 1]
    if not dims:
        return 1, 0, 0
    ok = True
    for j in range(len(dims) - 1):
        if dims[j][1] != dims[j + 1][1] * dims[j + 1][0]:
            ok = False
            break
    if ok:
        return 1, dims[-1][1], 0
    if len(dims) == 2:
        return dims[1][0], dims[0][1], dims[1][1]
    raise NotImplementedError("unsupported stride pattern")


def run(grad, dim, indices, sizes, keepdim):
    nd = len(sizes)
    d = dim + nd if dim < 0 else dim
    out = grad.new_empty(sizes)

    if d == nd - 1 and grad.is_contiguous() and indices.is_contiguous():
        m = grad.numel()
        k = sizes[-1]
        bk = triton.next_power_of_2(k)
        if bk > _MAX_BK:
            bk = _MAX_BK
        nchunk = (k + bk - 1) // bk
        r = (int(_TARGET_BYTES) // grad.element_size()) // bk
        if r < 1:
            r = 1
        elif r > m:
            r = triton.next_power_of_2(m)
        _fused_lastdim[((m + r - 1) // r, nchunk)](
            grad,
            indices,
            out,
            m,
            R=r,
            K=k,
            BK=bk,
            EVEN=(m % r) == 0,
            FULLK=(k == nchunk * bk),
        )
        return out

    # ---- general path: zero fill + strided scatter -------------------------
    outer = 1
    for s in sizes[:d]:
        outer *= s
    k = sizes[d]
    inner = 1
    for s in sizes[d + 1:]:
        inner *= s

    n = out.numel()
    _zero_kernel[(triton.cdiv(n, _ZERO_BLOCK),)](out, n, BLOCK=_ZERO_BLOCK)

    g_shape = list(grad.shape)
    g_st = list(grad.stride())
    if len(g_shape) == nd:
        del g_shape[d]
        del g_st[d]
    i_st = list(indices.stride())
    if len(i_st) == nd:
        del i_st[d]

    go_split, go_st0, go_st1 = _group(g_shape[:d], g_st[:d])
    gi_split, gi_st0, gi_st1 = _group(g_shape[d:], g_st[d:])
    io_split, io_st0, io_st1 = _group(g_shape[:d], i_st[:d])
    ii_split, ii_st0, ii_st1 = _group(g_shape[d:], i_st[d:])

    ns = grad.numel()
    _scatter_general[(triton.cdiv(ns, _SCATTER_BLOCK),)](
        grad,
        indices,
        out,
        ns,
        INNER=inner,
        K=k,
        GO_SPLIT=go_split,
        GO_ST0=go_st0,
        GO_ST1=go_st1,
        GI_SPLIT=gi_split,
        GI_ST0=gi_st0,
        GI_ST1=gi_st1,
        IO_SPLIT=io_split,
        IO_ST0=io_st0,
        IO_ST1=io_st1,
        II_SPLIT=ii_split,
        II_ST0=ii_st0,
        II_ST1=ii_st1,
        BLOCK=_SCATTER_BLOCK,
    )
    return out
