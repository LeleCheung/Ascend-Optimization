@triton.jit
def _zero_kernel(out_ptr, N, BLOCK: tl.constexpr):
    offs = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    zero = tl.zeros([BLOCK], dtype=out_ptr.dtype.element_ty)
    tl.store(out_ptr + offs, zero, mask=offs < N)


