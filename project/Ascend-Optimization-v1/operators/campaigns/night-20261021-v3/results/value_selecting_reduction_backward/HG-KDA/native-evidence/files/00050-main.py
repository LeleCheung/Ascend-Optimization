def _scatter_general(
    g_ptr,
    idx_ptr,
    out_ptr,
    N,
    INNER: tl.constexpr,
    K: tl.constexpr,
    GO_SPLIT: tl.constexpr,
    GO_ST0: tl.constexpr,
    GO_ST1: tl.constexpr,
    GI_SPLIT: tl.constexpr,
    GI_ST0: tl.constexpr,
    GI_ST1: tl.constexpr,
    IO_SPLIT: tl.constexpr,
    IO_ST0: tl.constexpr,
    IO_ST1: tl.constexpr,
    II_SPLIT: tl.constexpr,
    II_ST0: tl.constexpr,
    II_ST1: tl.constexpr,
    BLOCK: tl.constexpr,
):
    s = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    m = s < N
    o = s // INNER
    i = s % INNER
    g_off = (o // GO_SPLIT) * GO_ST0 + (o % GO_SPLIT) * GO_ST1
    g_off += (i // GI_SPLIT) * GI_ST0 + (i % GI_SPLIT) * GI_ST1
    i_off = (o // IO_SPLIT) * IO_ST0 + (o % IO_SPLIT) * IO_ST1
    i_off += (i // II_SPLIT) * II_ST0 + (i % II_SPLIT) * II_ST1
