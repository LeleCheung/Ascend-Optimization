# 现状 (8,1024) 每轮把一行切成 8 段 2KB 的跨步访问并串行 4 轮。
# 改法：BR = R = 4096（整行一次归约），BO 按片上预算取 max(1, 预算/R)：
#   fp16/bf16（NATIVE=True，累加器 2 字节）BO=4：acc (4,4096)=32KB，
#   tile 32KB，双缓冲 64KB，合计约 96KB；
#   fp32（NATIVE=False，累加器 4 字节）BO=2：acc (2,4096)=32KB，
#   tile 32KB，双缓冲 64KB，同约 96KB。
# 与 (8,1024) 的累加器/搬运元素数完全相同（各 8192），UB 占用等价，
# 不是靠扩大片上占用换性能；收益来自：内层循环 4 轮 -> 1 轮（去掉串行
# DMA 等待链）、BR==R 时 (BO,R) tile 覆盖 BO 个相邻整行从而变成一次连续
# DMA（fp16/bf16 32KB、fp32 32KB），取代每轮 8 段 2KB 跨步搬运。
@triton.jit
def amin_native_middle_kernel(X, Y, R: tl.constexpr, I: tl.constexpr,
           BC: tl.constexpr, BR: tl.constexpr, NATIVE: tl.constexpr,
           MASKED: tl.constexpr):
    outer = tl.program_id(0)
    cols = tl.program_id(1) * BC + tl.arange(0, BC)
    reds = tl.arange(0, BR)
    if NATIVE:
        acc = tl.full((BR, BC), float('inf'), X.dtype.element_ty)
    else:
        acc = tl.full((BR, BC), float('inf'), tl.float32)
    base = X + outer * R * I
    for start in range(tl.cdiv(R, BR)):
        r = start * BR + reds
        if MASKED:
            values = tl.load(base + r[:, None] * I + cols[None, :],
                             (r[:, None] < R) & (cols[None, :] < I), float('inf'))
        else:
            values = tl.load(base + r[:, None] * I + cols[None, :])
        acc = tl.minimum(acc, values.to(acc.dtype))
    value = tl.min(acc, axis=0)
    if MASKED:
        tl.store(Y + outer * I + cols, value, cols < I)
    else:
        tl.store(Y + outer * I + cols, value)


