# 本轮新增内核：中间维、且分块宽度恰好等于末维（BC == I）的扁平连续取数。
# 依据（同合同设备计时换算的逻辑字节速率）：fp32 在 (4096,4096)/(64,512,512)/
# (1024,1024,1024) 分别约 1.27/1.32/1.33 TB/s，fp16 在三个 3D 大 case 约
# 1.20/1.32 TB/s，两种 dtype 单位字节耗时相同 => 这三个 3D 中间维 case 的
# 上限由搬运侧决定，而不是元素数或向量算力；同 shape 的 tp 也只有 1.3~2.2 TB/s。
# 现有 amin_native_middle_kernel 对 (BR, BC) 用 r[:, None] * I + cols[None, :]
# 做二维取数：BC == I 时整块其实是连续的一段，但编译器一般只能证明末维连续，
# 于是每个 program 每轮会按行拆成 BR 段独立搬运（(1024^3) fp16 的 (16,1024)
# 是 16 段 2KB，间隔 2KB；(64,512,512) 的 (32,512) 是 32 段 1KB），
# 每轮 R/BR 次循环都要重复这套描述符与地址生成。
# 这里改成一次一维连续 tl.load(BR*BC 个元素)，累加器同样是一维，循环内无布局
# 变换，只在循环结束重排一次再按列 tl.min(axis=0)。归约集合完全相同。
@triton.jit
def amin_flat_middle_kernel(X, Y, R: tl.constexpr, I: tl.constexpr,
                            BC: tl.constexpr, BR: tl.constexpr,
                            NATIVE: tl.constexpr):
    outer = tl.program_id(0)
    base = X + outer * R * I
    offs = tl.arange(0, BR * BC)
    if NATIVE:
        acc = tl.full([BR * BC], float('inf'), X.dtype.element_ty)
    else:
        acc = tl.full([BR * BC], float('inf'), tl.float32)
    for start in range(tl.cdiv(R, BR)):
        values = tl.load(base + start * (BR * BC) + offs)
        acc = tl.minimum(acc, values.to(acc.dtype))
    # 一次重排即可：扁平槽位 j * BC + c 对应行槽 j、列 c（因为 BC == I）。
    tile = tl.reshape(acc, [BR, BC])
    value = tl.min(tile, axis=0)
    cols = tl.arange(0, BC)
    tl.store(Y + outer * I + cols, value)


