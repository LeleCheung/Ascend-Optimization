# ---------------------------------------------------------------------------
# Copy-free single-dimension kernels.
#
# For a contiguous input and a single reduction axis d the tensor can be seen
# as a dense (O, K, I) block (O = prod(shape[:d]), K = shape[d],
# I = prod(shape[d+1:])) with unit strides, so no materialised transpose /
# contiguous copy is needed.
#
#   * I == 1  -> plain row reduction of the (O, K) matrix over its last axis.
#   * I  > 1  -> reduction over the middle axis; a (BLOCK_K, BLOCK_I) tile is a
#                contiguous run of BLOCK_K*BLOCK_I elements whenever
#                BLOCK_I == I, so the load stays fully coalesced.
#
# Min is exact in the operand dtype (it selects one of its inputs), therefore
# the accumulation is carried in the input dtype and every result is
# bit-identical to a higher precision accumulator.
# ---------------------------------------------------------------------------


@libentry()
@triton.jit
def amin_last_kernel(
    x_ptr,
    out_ptr,
    M,
    N,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    dtype = x_ptr.dtype.element_ty
    acc_type = tl.float32 if dtype is tl.bfloat16 else dtype
    pid = tl.program_id(0)
    rows = pid * BLOCK_M + tl.arange(0, BLOCK_M)
    rmask = rows < M
    acc = tl.full([BLOCK_M, BLOCK_N], float("inf"), dtype=acc_type)
    for off in range(0, N, BLOCK_N):
        cols = off + tl.arange(0, BLOCK_N)
        cmask = cols < N
        val = tl.load(
            x_ptr + rows[:, None] * N + cols[None, :],
            mask=rmask[:, None] & cmask[None, :],
            other=float("inf"),
        )
        acc = tl.minimum(acc, val.to(acc_type))
    tl.store(out_ptr + rows, tl.min(acc, axis=1).to(dtype), mask=rmask)


