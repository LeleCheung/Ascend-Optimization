def _amin_last(mat, out_flat, M, N):
    """Reduce the (M, N) contiguous matrix over its last axis."""
    bn = min(triton.next_power_of_2(N), 2048)
    bm = max(1, 4096 // bn)
    bm = min(bm, max(1, triton.next_power_of_2(M)))

    # Very few rows with a wide reduction: split the reduction axis so that the
    # device is filled with independent programs, then combine the partials.
    if M <= 32 and N >= 65536:
        s = max(1, min(1024, triton.cdiv(N, 16384)))
        chunk = triton.cdiv(N, s)
        block = min(triton.next_power_of_2(chunk), 4096)
        mid = torch.empty((M * s,), dtype=mat.dtype, device=mat.device)
        amin_split_kernel[(M, s)](mat, mid, M, N, s, chunk, BLOCK=block)
        amin_split_final_kernel[(1,)](
            mid,
            out_flat,
            M,
            s,
            BLOCK_M=max(1, triton.next_power_of_2(M)),
            BLOCK_S=triton.next_power_of_2(s),
        )
        return

    if triton.cdiv(M, bm) > 65535:
        bm = triton.next_power_of_2(triton.cdiv(M, 65535))
        while bm * bn > 8192 and bn > 1:
            bn //= 2
    amin_last_kernel[(triton.cdiv(M, bm),)](mat, out_flat, M, N, BLOCK_M=bm, BLOCK_N=bn)


def _amin_mid(mat, out_flat, O, K, I):
    """Reduce the (O, K, I) contiguous block over its middle axis."""
    bi = min(triton.next_power_of_2(I), 1024)
    bk = min(256, max(1, 8192 // bi))
    gi = triton.cdiv(I, bi)

    # Keep every program's element span inside int32 and the launch grid inside
    # the device core-dim limit.
    max_o = max(1, (2**31 - 1) // max(1, K * I))
    chunk_o = min(65535, max_o)
    if chunk_o >= O:
        amin_mid_kernel[(O, gi)](mat, out_flat, K, I, BLOCK_I=bi, BLOCK_K=bk)
    else:
        for start in range(0, O, chunk_o):
            rows = min(chunk_o, O - start)
            amin_mid_kernel[(rows, gi)](
                mat.narrow(0, start, rows),
                out_flat.narrow(0, start * I, rows * I),
                K,
                I,
                BLOCK_I=bi,
                BLOCK_K=bk,
            )


def _amin_single_dim(inp, d, keepdim):
    shape = list(inp.shape)
    ndim = len(shape)
    K = shape[d]
    I = 1
    for ax in range(d + 1, ndim):
        I *= shape[ax]
    O = 1
    for ax in range(0, d):
        O *= shape[ax]

    out_shape = list(shape)
    out_shape[d] = 1
    out = torch.empty(out_shape, dtype=inp.dtype, device=inp.device)
    out_flat = out.view(-1)

    with torch_device_fn.device(inp.device):
        if I == 1:
            _amin_last(inp.view(O, K), out_flat, O, K)
        else:
            _amin_mid(inp.view(O, K, I), out_flat, O, K, I)

    if not keepdim:
        out = out.squeeze(d)
    return out


def amin(inp, dim=None, keepdim=False):
    logger.debug("GEMS AMIN")
    assert inp.dtype in (
        torch.float32,
        torch.float16,
        torch.bfloat16,
    ), "amin only supports float dtypes"
    if dim is None or len(dim) == 0:
        M = inp.numel()
        block_size = triton.next_power_of_2(math.ceil(math.sqrt(M)))
        mid_size = triton.cdiv(M, block_size)
        block_mid = triton.next_power_of_2(mid_size)
        dtype = inp.dtype
        mid = torch.empty((mid_size,), dtype=dtype, device=inp.device)
        if not keepdim:
            out = torch.empty([], dtype=dtype, device=inp.device)
        else:
            shape = list(inp.shape)
            for i in range(0, inp.dim()):
                shape[i] = 1
            out = torch.empty(shape, dtype=dtype, device=inp.device)
        with torch_device_fn.device(inp.device):
            amin_kernel_1[(mid_size, 1)](
                inp,
                mid,
                M,
                block_size,
            )
            amin_kernel_2[(1, 1)](
                mid, out, mid_size, block_mid
            )  # max block size is 128k, so mid does not requires int64 index
        return out

    dims = [d % inp.ndim for d in dim]
    if inp.is_contiguous() and len(set(dims)) == 1:
        return _amin_single_dim(inp, dims[0], keepdim)

    if isinstance(dim, int):
        dim = [dim]
    assert ((i >= -inp.ndim and i < inp.ndim) for i in dim), "Invalid dim"
    dtype = inp.dtype

    shape = list(inp.shape)
    dim = [d % inp.ndim for d in dim]
    inp = dim_compress(inp, dim)
    N = 1
    for i in dim:
        N *= shape[i]
        shape[i] = 1
    M = inp.numel() // N

    out = torch.empty(shape, dtype=dtype, device=inp.device)

    with torch_device_fn.device(inp.device):
        if M <= 65535:
            grid = lambda meta: (triton.cdiv(M, meta["BLOCK_M"]),)
            amin_kernel[grid](inp, out, M, N)
        else:
            # Ascend coreDim <= 65535；拆分行范围，原内核与调优配置不变。
            # 即使 autotune 选择 BLOCK_M=1，每次启动也不会超限。
            flat_input = inp.reshape(-1)
            flat_output = out.reshape(-1)
            for start in range(0, M, 65528):
                rows = min(65528, M - start)
                grid = lambda meta: (triton.cdiv(rows, meta["BLOCK_M"]),)
                amin_kernel[grid](flat_input[start * N:], flat_output[start:], rows, N)
    if not keepdim:
        out = out.squeeze(dim=dim)
    return out


