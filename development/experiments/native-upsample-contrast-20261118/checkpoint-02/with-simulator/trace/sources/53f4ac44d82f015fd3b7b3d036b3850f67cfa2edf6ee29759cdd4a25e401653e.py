def upsample_bilinear2d_2x_kernel(
    ptr_o,
    ptr_i,
    IH,
    IW,
    OH,
    OW,
    TAIL: tl.constexpr,
    BLOCK_J: tl.constexpr,
):
    # Exact-2x bilinear upsampling with align_corners=False.
    #
    # For scale exactly 2 the pixel-centre mapping degenerates to fixed weights:
    #   output row 2*i     = 0.25 * in[i-1] + 0.75 * in[i]
    #   output row 2*i + 1 = 0.75 * in[i]   + 0.25 * in[i+1]
    # and the same pair of weights applies along the width, so every input
    # element of the (i-1, i, i+1) x (j-1, j, j+1) stencil is reached with an
    # affine, contiguous address.  (n, c) and the input row are grid axes, so
    # the kernel has no serial slice loop.
    pid_j = tl.program_id(axis=0)
    i = tl.program_id(axis=1)
    nc = tl.program_id(axis=2)

    j = pid_j * BLOCK_J + tl.arange(0, BLOCK_J)
    b2 = tl.arange(0, 2)

    # Edge clamping keeps the fixed weights exact at the image border.
    m_left = j > 0
    m_right = j < (IW - 1)
    if TAIL:
        j_ok = j < IW
        m_left = m_left & j_ok
        m_right = m_right & j_ok

    im = tl.maximum(i - 1, 0)
    ip = tl.minimum(i + 1, IH - 1)

    base_i = nc.to(tl.int64) * IH * IW
    row_m = ptr_i + (base_i + im * IW)
    row_c = ptr_i + (base_i + i * IW)
    row_p = ptr_i + (base_i + ip * IW)

    ml = tl.load(row_m + (j - 1), mask=m_left, other=0.0).to(tl.float32)
    mr = tl.load(row_m + (j + 1), mask=m_right, other=0.0).to(tl.float32)
    cl = tl.load(row_c + (j - 1), mask=m_left, other=0.0).to(tl.float32)
    cr = tl.load(row_c + (j + 1), mask=m_right, other=0.0).to(tl.float32)
    pl = tl.load(row_p + (j - 1), mask=m_left, other=0.0).to(tl.float32)
    pr = tl.load(row_p + (j + 1), mask=m_right, other=0.0).to(tl.float32)
    if TAIL:
        mc = tl.load(row_m + j, mask=j_ok, other=0.0).to(tl.float32)
        cc = tl.load(row_c + j, mask=j_ok, other=0.0).to(tl.float32)
        pc = tl.load(row_p + j, mask=j_ok, other=0.0).to(tl.float32)
    else:
        mc = tl.load(row_m + j).to(tl.float32)
        cc = tl.load(row_c + j).to(tl.float32)
        pc = tl.load(row_p + j).to(tl.float32)

    # Replace the masked lanes by the clamped (edge) sample in registers.
    ml = tl.where(j > 0, ml, mc)
    mr = tl.where(j < (IW - 1), mr, mc)
    cl = tl.where(j > 0, cl, cc)
    cr = tl.where(j < (IW - 1), cr, cc)
    pl = tl.where(j > 0, pl, pc)
    pr = tl.where(j < (IW - 1), pr, pc)

    # Vertical half of the separable interpolation.
    e_l = 0.25 * ml + 0.75 * cl
    e_c = 0.25 * mc + 0.75 * cc
    e_r = 0.25 * mr + 0.75 * cr
    o_l = 0.75 * cl + 0.25 * pl
    o_c = 0.75 * cc + 0.25 * pc
    o_r = 0.75 * cr + 0.25 * pr

    # Horizontal half, laid out as (BLOCK_J, 2) column pairs so that both
    # stores are contiguous in the output row.
    pair_e = tl.where(
        b2[None, :] == 0,
        (0.25 * e_l + 0.75 * e_c)[:, None],
        (0.75 * e_c + 0.25 * e_r)[:, None],
    )
    pair_o = tl.where(
        b2[None, :] == 0,
        (0.25 * o_l + 0.75 * o_c)[:, None],
        (0.75 * o_c + 0.25 * o_r)[:, None],
    )

    col = 2 * j[:, None] + b2[None, :]
    out0 = nc.to(tl.int64) * OH * OW + (2 * i) * OW
    if TAIL:
        m_store = (j < IW)[:, None] & (b2[None, :] < 2)
        tl.store(ptr_o + out0 + col, pair_e, mask=m_store)
        tl.store(ptr_o + out0 + OW + col, pair_o, mask=m_store)
    else:
        tl.store(ptr_o + out0 + col, pair_e)
        tl.store(ptr_o + out0 + OW + col, pair_o)


def bilinear_reciprocal_scale(src_size, dst_size, align_corners, scale):
    if align_corners:
        if dst_size > 1:
            return (src_size - 1) / (dst_size - 1)
        else:
            return 0.0
    else:
        if scale is not None and scale > 0:
            return 1.0 / scale
        else:
            return src_size / dst_size


def upsample_bilinear2d(
    input: torch.Tensor,
    output_size: Tuple[int],
    align_corners: bool = False,
    scales_h: Optional[float] = None,
    scales_w: Optional[float] = None,
) -> torch.Tensor:
    assert input.device.type in ("npu", "privateuseone")
    assert input.ndim == 4, "The ndim of input must be 4"
    assert len(output_size) == 2, "The len of output_size must be 2"

    OH, OW = output_size
    N, C, IH, IW = input.shape

    reciprocal_scale_h = bilinear_reciprocal_scale(IH, OH, align_corners, scales_h)
    reciprocal_scale_w = bilinear_reciprocal_scale(IW, OW, align_corners, scales_w)

    # Allocate output
    output = torch.empty((N, C, OH, OW), device=input.device, dtype=input.dtype)

    # Exact-2x fast path: with scale == 2 and align_corners == False the
    # bilinear weights are the constants 0.25/0.75 on both axes, so the kernel
    # needs no data-dependent input address at all.  Selection uses only the
    # runtime metadata of the call (shapes, align_corners, effective scale).
    use_exact_2x = (
        (not align_corners)
        and OH == 2 * IH
        and OW == 2 * IW
        and reciprocal_scale_h == 0.5
        and reciprocal_scale_w == 0.5
    )
    if use_exact_2x:
        block_j = 128
        tail = (IW % block_j) != 0
        with device_context(input.device):
            upsample_bilinear2d_2x_kernel[
                (triton.cdiv(IW, block_j), IH, N * C)
            ](
                output,
                input,
                IH,
                IW,
                OH,
                OW,
                tail,
                block_j,
            )
        return output

    grid = lambda META: (
        triton.cdiv(OW, META["BLOCK_X"]),
        triton.cdiv(OH, META["BLOCK_Y"]),
    )

    with device_context(input.device):
        upsample_bilinear2d_kernel[grid](
            output,
            input,
            N,
            C,
            OH,
            OW,
            IH,
            IW,
            reciprocal_scale_h,
            reciprocal_scale_w,
            align_corners,
        )
    return output


