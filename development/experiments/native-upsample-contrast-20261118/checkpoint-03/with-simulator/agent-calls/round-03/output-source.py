def upsample_bilinear2d_kernel(
    ptr_o,
    ptr_i,
    N,
    C,
    OH,
    OW,
    IH,
    IW,
    reciprocal_scale_h,
    reciprocal_scale_w,
    ALIGN_CORNERS: tl.constexpr,
    BLOCK_X: tl.constexpr,
    BLOCK_Y: tl.constexpr,
):
    pid_x = tl.program_id(axis=0)
    pid_y = tl.program_id(axis=1)
    ow = (pid_x * BLOCK_X + tl.arange(0, BLOCK_X)) % OW
    oh = (pid_y * BLOCK_Y + tl.arange(0, BLOCK_Y)) % OH

    # Compute the source coordinates
    if ALIGN_CORNERS:
        # When align_corners is True, map corners to corners
        # real_h = oh * (IH - 1) / (OH - 1) when OH > 1
        real_h = tl.where(
            OH > 1,
            oh.to(tl.float32) * (IH - 1) / (OH - 1),
            tl.zeros_like(oh).to(tl.float32),
        )
        real_w = tl.where(
            OW > 1,
            ow.to(tl.float32) * (IW - 1) / (OW - 1),
            tl.zeros_like(ow).to(tl.float32),
        )
    else:
        # When align_corners is False, use area-based scaling
        # real_h = (oh + 0.5) * scale_h - 0.5
        real_h = (oh.to(tl.float32) + 0.5) * reciprocal_scale_h - 0.5
        real_w = (ow.to(tl.float32) + 0.5) * reciprocal_scale_w - 0.5

    # Clamp to valid range
    real_h = tl.maximum(real_h, 0.0)
    real_w = tl.maximum(real_w, 0.0)

    # Get integer parts (top-left corner of the 2x2 region)
    h0 = real_h.to(tl.int32)
    w0 = real_w.to(tl.int32)

    # Clamp to ensure we don't go out of bounds
    h0 = tl.minimum(h0, IH - 1)
    w0 = tl.minimum(w0, IW - 1)
    h1 = tl.minimum(h0 + 1, IH - 1)
    w1 = tl.minimum(w0 + 1, IW - 1)

    # Compute interpolation weights
    h_weight = real_h - h0.to(tl.float32)
    w_weight = real_w - w0.to(tl.float32)

    # Clamp weights to [0, 1]
    h_weight = tl.maximum(tl.minimum(h_weight, 1.0), 0.0)
    w_weight = tl.maximum(tl.minimum(w_weight, 1.0), 0.0)

    # Compute bilinear weights
    w00 = (1.0 - h_weight[:, None]) * (1.0 - w_weight[None, :])
    w01 = (1.0 - h_weight[:, None]) * w_weight[None, :]
    w10 = h_weight[:, None] * (1.0 - w_weight[None, :])
    w11 = h_weight[:, None] * w_weight[None, :]

    # Process all N*C slices
    for n in range(0, N, 1):
        for c in range(0, C, 1):
            # Compute base offset for input
            base_offset = (n * C + c) * IH

            # Load the 4 neighbors
            offset_00 = (base_offset + h0[:, None]) * IW + w0[None, :]
            offset_01 = (base_offset + h0[:, None]) * IW + w1[None, :]
            offset_10 = (base_offset + h1[:, None]) * IW + w0[None, :]
            offset_11 = (base_offset + h1[:, None]) * IW + w1[None, :]

            data_00 = tl.load(ptr_i + offset_00)
            data_01 = tl.load(ptr_i + offset_01)
            data_10 = tl.load(ptr_i + offset_10)
            data_11 = tl.load(ptr_i + offset_11)

            # Compute bilinear interpolation
            result = (
                data_00.to(tl.float32) * w00
                + data_01.to(tl.float32) * w01
                + data_10.to(tl.float32) * w10
                + data_11.to(tl.float32) * w11
            )

            # Store result (explicit cast so the store operand type always
            # matches the output pointer element type)
            offset_o = ((n * C + c) * OH + oh[:, None]) * OW + ow[None, :]
            tl.store(ptr_o + offset_o, result.to(ptr_o.dtype.element_ty))


@triton.jit
def upsample_bilinear2d_2x_kernel(
    ptr_o,
    ptr_i,
    IH,
    IW,
    OH,
    OW,
    TAIL: tl.constexpr,
    BLOCK_J: tl.constexpr,
):
    # Exact-2x bilinear upsampling with align_corners=False.
    #
    # For scale exactly 2 the pixel-centre mapping degenerates to fixed weights:
    #   output row 2*i     = 0.25 * in[i-1] + 0.75 * in[i]
    #   output row 2*i + 1 = 0.75 * in[i]   + 0.25 * in[i+1]
    # and the same pair of weights applies along the width, so every input
    # element of the (i-1, i, i+1) x (j-1, j, j+1) stencil is reached with an
    # affine, contiguous address.
    #
    # Every tensor here is one-dimensional with width BLOCK_J.  Edge handling is
    # folded into clamped column indices (jl/jr), so no load needs a mask plus a
    # select on the loaded value, and the two output columns produced by one
    # input column are written by two stride-2 stores per output row.  The
    # kernel therefore keeps a BLOCK_J-wide vector layout end to end instead of
    # the 2-wide innermost dimension of a (BLOCK_J, 2) pair tile.  (n, c) and
    # the input row are grid axes, so there is no serial slice loop either.
    pid_j = tl.program_id(axis=0)
    i = tl.program_id(axis=1)
    nc = tl.program_id(axis=2)

    j = pid_j * BLOCK_J + tl.arange(0, BLOCK_J)
    if TAIL:
        # Inactive lanes are folded onto the last valid column so that every
        # load address stays inside the allocation; only the stores are masked.
        m_store = j < IW
        j = tl.minimum(j, IW - 1)

    jl = tl.maximum(j - 1, 0)
    jr = tl.minimum(j + 1, IW - 1)
    im = tl.maximum(i - 1, 0)
    ip = tl.minimum(i + 1, IH - 1)

    base_i = nc.to(tl.int64) * IH * IW
    row_m = ptr_i + (base_i + im * IW)
    row_c = ptr_i + (base_i + i * IW)
    row_p = ptr_i + (base_i + ip * IW)

    ml = tl.load(row_m + jl).to(tl.float32)
    mc = tl.load(row_m + j).to(tl.float32)
    mr = tl.load(row_m + jr).to(tl.float32)
    cl = tl.load(row_c + jl).to(tl.float32)
    cc = tl.load(row_c + j).to(tl.float32)
    cr = tl.load(row_c + jr).to(tl.float32)
    pl = tl.load(row_p + jl).to(tl.float32)
    pc = tl.load(row_p + j).to(tl.float32)
    pr = tl.load(row_p + jr).to(tl.float32)

    # Vertical half of the separable interpolation: output row 2*i blends rows
    # (i-1, i) with weights (0.25, 0.75), output row 2*i+1 blends rows
    # (i, i+1) with weights (0.75, 0.25).
    e_l = 0.25 * ml + 0.75 * cl
    e_c = 0.25 * mc + 0.75 * cc
    e_r = 0.25 * mr + 0.75 * cr
    o_l = 0.75 * cl + 0.25 * pl
    o_c = 0.75 * cc + 0.25 * pc
    o_r = 0.75 * cr + 0.25 * pr

    # Horizontal half: output column 2*j takes (0.25, 0.75) on columns
    # (j-1, j), output column 2*j+1 takes (0.75, 0.25) on columns (j, j+1).
    col_e = 2 * j
    out_dtype = ptr_o.dtype.element_ty
    out_even_row = nc.to(tl.int64) * OH * OW + (2 * i) * OW
    out_odd_row = out_even_row + OW

    ev = (0.25 * e_l + 0.75 * e_c).to(out_dtype)
    od = (0.75 * e_c + 0.25 * e_r).to(out_dtype)
    ev2 = (0.25 * o_l + 0.75 * o_c).to(out_dtype)
    od2 = (0.75 * o_c + 0.25 * o_r).to(out_dtype)

    if TAIL:
        tl.store(ptr_o + out_even_row + col_e, ev, mask=m_store)
        tl.store(ptr_o + out_even_row + col_e + 1, od, mask=m_store)
        tl.store(ptr_o + out_odd_row + col_e, ev2, mask=m_store)
        tl.store(ptr_o + out_odd_row + col_e + 1, od2, mask=m_store)
    else:
        tl.store(ptr_o + out_even_row + col_e, ev)
        tl.store(ptr_o + out_even_row + col_e + 1, od)
        tl.store(ptr_o + out_odd_row + col_e, ev2)
        tl.store(ptr_o + out_odd_row + col_e + 1, od2)


def bilinear_reciprocal_scale(src_size, dst_size, align_corners, scale):
    if align_corners:
        if dst_size > 1:
            return (src_size - 1) / (dst_size - 1)
        else:
            return 0.0
    else:
        if scale is not None and scale > 0:
            return 1.0 / scale
        else:
            return src_size / dst_size


def upsample_bilinear2d(
    input: torch.Tensor,
    output_size: Tuple[int],
    align_corners: bool = False,
    scales_h: Optional[float] = None,
    scales_w: Optional[float] = None,
) -> torch.Tensor:
    assert input.device.type in ("npu", "privateuseone")
    assert input.ndim == 4, "The ndim of input must be 4"
    assert len(output_size) == 2, "The len of output_size must be 2"

    OH, OW = output_size
    N, C, IH, IW = input.shape

    reciprocal_scale_h = bilinear_reciprocal_scale(IH, OH, align_corners, scales_h)
    reciprocal_scale_w = bilinear_reciprocal_scale(IW, OW, align_corners, scales_w)

    # Allocate output
    output = torch.empty((N, C, OH, OW), device=input.device, dtype=input.dtype)

    # Exact-2x fast path: with scale == 2 and align_corners == False the
    # bilinear weights are the constants 0.25/0.75 on both axes, so the kernel
    # needs no data-dependent input address at all.  Selection uses only the
    # runtime metadata of the call (shapes, align_corners, effective scale).
    use_exact_2x = (
        (not align_corners)
        and OH == 2 * IH
        and OW == 2 * IW
        and reciprocal_scale_h == 0.5
        and reciprocal_scale_w == 0.5
    )
    if use_exact_2x:
        block_j = 128
        tail = (IW % block_j) != 0
        with device_context(input.device):
            upsample_bilinear2d_2x_kernel[
                (triton.cdiv(IW, block_j), IH, N * C)
            ](
                output,
                input,
                IH,
                IW,
                OH,
                OW,
                tail,
                block_j,
            )
        return output

    block_x, block_y = select_block_shape(OW)
    grid = (triton.cdiv(OW, block_x), triton.cdiv(OH, block_y))

    with device_context(input.device):
        upsample_bilinear2d_kernel[grid](
            output,
            input,
            N,
            C,
            OH,
            OW,
            IH,
            IW,
            reciprocal_scale_h,
            reciprocal_scale_w,
            align_corners,
            block_x,
            block_y,
        )
    return output


