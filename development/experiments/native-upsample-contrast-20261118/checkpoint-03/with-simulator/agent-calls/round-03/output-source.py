def device_context(device):
    npu = getattr(torch, "npu", None)
    if npu is not None:
        return npu.device(device)
    return _NullDeviceContext()


def select_block_shape(OW):
    """Static tile choice for the generic kernel, taken from the same
    BLOCK_X family as the native tuned metadata (64/128/256/512 x 1/2).
    Metadata only: the device-side autotuner is deliberately not used
    because its benchmark path calls a non-metadata ATen entry."""
    if OW >= 256:
        return 256, 1
    if OW >= 128:
        return 128, 1
    if OW >= 64:
        return 64, 1
    block_x = 32
    while block_x < OW and block_x < 512:
        block_x *= 2
    return block_x, 1


