def _hrow_2x(ptr_i, base, IW, j, m, BLOCK_OW: tl.constexpr):
    # Horizontally bilinear-expand one contiguous source row by 2x.
    # For align_corners=False and an exact 2x factor the source coordinate of
    # output column w is 0.5*w - 0.25, so the two column classes are fixed
    # blends of the current element and its left/right neighbour:
    #   even columns: 0.25*left  + 0.75*cur
    #   odd  columns: 0.75*cur   + 0.25*right
    # Every address below is an affine (stride 1) function of the lane index,
    # so the loads lower to contiguous DMA copies instead of scalar gathers.
    x = tl.load(ptr_i + base + j, mask=m, other=0.0).to(tl.float32)
    xr = tl.load(ptr_i + base + j - 1, mask=m & (j >= 1), other=0.0).to(tl.float32)
    xr = tl.where(j >= 1, xr, x)
    xl = tl.load(ptr_i + base + j + 1, mask=m & (j < IW - 1), other=0.0).to(tl.float32)
    xl = tl.where(j < IW - 1, xl, x)
    xe = 0.25 * xr + 0.75 * x
    xo = 0.75 * x + 0.25 * xl
    return tl.reshape(tl.join(xe, xo), (BLOCK_OW,))


