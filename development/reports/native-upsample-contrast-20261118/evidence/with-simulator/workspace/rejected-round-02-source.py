def upsample_bilinear2d_2x_kernel(
    ptr_o,
    ptr_i,
    IH,
    IW,
    OH,
    OW,
    ROWS: tl.constexpr,
    BLOCK_J: tl.constexpr,
    MASKED: tl.constexpr,
):
    # Exact-2x bilinear upsampling with align_corners=False.
    #
    # For scale exactly 2 the pixel-centre mapping degenerates to fixed weights:
    #   output row 2*i     = 0.25 * in[i-1] + 0.75 * in[i]
    #   output row 2*i + 1 = 0.75 * in[i]   + 0.25 * in[i+1]
    # and the same pair of weights applies along the width, so every input
    # element of the (i-1, i, i+1) x (j-1, j, j+1) stencil is reached with an
    # affine, contiguous address.
    #
    # Each program covers a ROWS x BLOCK_J tile of the input, i.e. ROWS input
    # rows and up to BLOCK_J input columns, and produces the corresponding
    # 2*ROWS output rows.  Row-tiling keeps the number of programs small and
    # makes every load one contiguous multi-row transfer instead of one
    # 256-byte row fragment, so the fixed per-program cost is amortised over
    # 8x more output.
    pid_j = tl.program_id(axis=0)
    pid_i = tl.program_id(axis=1)
    nc = tl.program_id(axis=2)

    j = pid_j * BLOCK_J + tl.arange(0, BLOCK_J)  # (BLOCK_J,)
    i = pid_i * ROWS + tl.arange(0, ROWS)  # (ROWS,)
    b2 = tl.arange(0, 2)

    # Edge clamping is done on the *addresses*: for j == 0 the left sample
    # degenerates to the centre sample, which is exactly PyTorch's border
    # replication, so no mask and no register fix-up select are needed.
    jl = tl.maximum(j - 1, 0)
    jr = tl.minimum(j + 1, IW - 1)
    jc = tl.minimum(j, IW - 1)  # in bounds even in the width tail

    im = tl.minimum(tl.maximum(i - 1, 0), IH - 1)
    ic = tl.minimum(i, IH - 1)  # in bounds even in the row tail
    ip = tl.minimum(i + 1, IH - 1)

    base_i = nc.to(tl.int64) * IH * IW
    row_m = ptr_i + (base_i + im * IW)[:, None]
    row_c = ptr_i + (base_i + ic * IW)[:, None]
    row_p = ptr_i + (base_i + ip * IW)[:, None]

    ml = tl.load(row_m + jl[None, :]).to(tl.float32)
    mc = tl.load(row_m + jc[None, :]).to(tl.float32)
    mr = tl.load(row_m + jr[None, :]).to(tl.float32)
    cl = tl.load(row_c + jl[None, :]).to(tl.float32)
    cc = tl.load(row_c + jc[None, :]).to(tl.float32)
    cr = tl.load(row_c + jr[None, :]).to(tl.float32)
    pl = tl.load(row_p + jl[None, :]).to(tl.float32)
    pc = tl.load(row_p + jc[None, :]).to(tl.float32)
    pr = tl.load(row_p + jr[None, :]).to(tl.float32)

    # Vertical half of the separable interpolation.
    e_l = 0.25 * ml + 0.75 * cl
    e_c = 0.25 * mc + 0.75 * cc
    e_r = 0.25 * mr + 0.75 * cr
    o_l = 0.75 * cl + 0.25 * pl
    o_c = 0.75 * cc + 0.25 * pc
    o_r = 0.75 * cr + 0.25 * pr

    # Horizontal half, laid out as (ROWS, BLOCK_J, 2) column pairs so that both
    # stores stay contiguous inside an output row.
    pair_e = tl.where(
        b2[None, None, :] == 0,
        (0.25 * e_l + 0.75 * e_c)[:, :, None],
        (0.75 * e_c + 0.25 * e_r)[:, :, None],
    )
    pair_o = tl.where(
        b2[None, None, :] == 0,
        (0.25 * o_l + 0.75 * o_c)[:, :, None],
        (0.75 * o_c + 0.25 * o_r)[:, :, None],
    )

    col = (2 * j)[None, :, None] + b2[None, None, :]
    out0 = nc.to(tl.int64) * OH * OW + (2 * i)[:, None, None] * OW
    if MASKED:
        m_store = (i < IH)[:, None, None] & (j < IW)[None, :, None]
        tl.store(ptr_o + out0 + col, pair_e, mask=m_store)
        tl.store(ptr_o + out0 + OW + col, pair_o, mask=m_store)
    else:
        tl.store(ptr_o + out0 + col, pair_e)
        tl.store(ptr_o + out0 + OW + col, pair_o)


def _bilinear_reciprocal_scale(src_size, dst_size, align_corners, scale):
    if align_corners:
        if dst_size > 1:
            return (src_size - 1) / (dst_size - 1)
        else:
            return 0.0
    else:
        if scale is not None and scale > 0:
            return 1.0 / scale
        else:
            return src_size / dst_size


