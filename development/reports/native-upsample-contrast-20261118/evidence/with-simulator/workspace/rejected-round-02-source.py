    # Allocate output
    output = torch.empty((N, C, OH, OW), device=input.device, dtype=input.dtype)

    # Exact-2x fast path: with scale == 2 and align_corners == False the
    # bilinear weights are the constants 0.25/0.75 on both axes, so the kernel
    # needs no data-dependent input address at all.  Selection uses only the
    # runtime metadata of the call (shapes, align_corners, effective scale).
