        # seq_len % BLOCK_S == 0: no masking at all, which keeps every
        # transfer a full block.
        q_val = tl.load(q_in)
        k_val = tl.load(q_in + k_shift)
        v_val = tl.load(q_in + v_shift)

        q_bias = tl.load(bias_cols)
        k_bias = tl.load(bias_cols + k_bias_shift)
        v_bias = tl.load(bias_cols + v_bias_shift)

        # Reference numeric order: bias add and rescale happen in float32
        # opmath and the result is rounded to the output dtype once. Adding in
