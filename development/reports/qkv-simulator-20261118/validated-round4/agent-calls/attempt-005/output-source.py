        q_bias = tl.load(bias_cols, mask=col_mask, other=0.0)
        k_bias = tl.load(bias_cols + k_bias_shift, mask=col_mask, other=0.0)
        v_bias = tl.load(bias_cols + v_bias_shift, mask=col_mask, other=0.0)

