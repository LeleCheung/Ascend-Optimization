import torch
import triton
import triton.language as tl

# Element budget of one [BLOCK_S, BLOCK_H, BLOCK_D] tile (bytes). Six such
# tiles (q/k/v in and out) are live at once, so 8192 keeps ~48 KB of the AIV
# UB in use. Each program carries one short serial load->vector->store chain,
# so a larger tile halves the program count and amortizes the fixed
# per-program DMA/launch latency over twice the useful bytes.
#
# Budget note (UB overflow): besides the six data tiles the kernel also stages
# the 3D int64 offset tensors (q_in, out_off: 8 B/element each) and the fp32
# q opmath temporaries, i.e. ~34 B per tile element in the AIV UB. A 16384 B
# budget (8192 elements, e.g. [BLOCK_S=32, BLOCK_H=4, BLOCK_D=64] for fp16
# head_dim 64) therefore needed ~262 KiB and failed compilation with
# "ub overflow, requires 2146304 bits while 1572864 bits available"
# (192 KiB UB). 8192 B keeps the tile at 4096 elements (~139 KiB) and, since
# address arithmetic is unchanged, only the partitioning changes.
#
# The input is [batch, seq, 3*hidden]; for one head only head_dim consecutive
# columns are contiguous, so the old [BLOCK_S, BLOCK_D] tile read 128 B rows
# with a 6 KB stride while its output store was one fully contiguous block.
# Grouping BLOCK_H adjacent heads widens each input row to
# BLOCK_H*head_dim contiguous elements, matching the store-side granularity.
# BLOCK_S is reduced to keep the same element budget, so the program count,
# bytes moved and arithmetic are unchanged.
_TILE_BYTES = 8192
# Keep every per-head output store at least this large so the store lane does
# not fragment into sub-burst transfers. Still two DMA bursts' worth, and it
# lets BLOCK_H keep grouping adjacent heads when the tile budget is halved.
_MIN_STORE_BYTES = 2048


