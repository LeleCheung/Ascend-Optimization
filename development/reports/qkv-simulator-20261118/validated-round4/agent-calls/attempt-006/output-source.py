import torch
import triton
import triton.language as tl

# Element budget of one [BLOCK_S, BLOCK_H, BLOCK_D] tile (bytes). One program
# carries one short serial load->compute->store chain per component, so a
# larger tile reduces the program count and amortizes the fixed per-program
# DMA/launch latency over more useful bytes.
#
# Budget note (UB overflow, measured): the AIV UB estimate is driven by the tile
# ELEMENT count times the number of simultaneously live full-tile tensors, and
# the dominant term is address arithmetic - every tt.load/tt.store keeps a
# tensor<...x!tt.ptr<f16>> of 8 B/element (3 input pointers + 3 output
# pointers), plus a 4 B/element index tensor and the fp32 q opmath chain. A
# byte budget alone is therefore not the right control: with _TILE_BYTES=8192
# an fp16 specialization still materialized [32, 4, 16] = 2048 elements (BLOCK_S
# capped by next_power_of_2(seq_len)) and BiShengHIR rejected it with
# "ub overflow, requires 2146304 bits while 1572864 bits available"
# (268288 B required, 192 KiB available; ~131 B per tile element).
# 2048 B caps an fp16 tile at 1024 elements (512 for fp32), and the three
# components are additionally emitted as sequential phases so at most one input
# and one output pointer tensor is live at a time.
#
# The input is [batch, seq, 3*hidden]; for one head only head_dim consecutive
# columns are contiguous, so the old [BLOCK_S, BLOCK_D] tile read 128 B rows
# with a 6 KB stride while its output store was one fully contiguous block.
# Grouping BLOCK_H adjacent heads widens each input row to
# BLOCK_H*head_dim contiguous elements, matching the store-side granularity.
# BLOCK_S is reduced to keep the same element budget, so the program count,
# bytes moved and arithmetic are unchanged.
_TILE_BYTES = 2048
# Keep every per-head output store at least this large so the store lane does
# not fragment into sub-burst transfers. Scaled down with _TILE_BYTES so
# BLOCK_H can still group adjacent heads (and thereby keep each input row wide)
# instead of degenerating to BLOCK_H == 1 at the smaller element budget.
_MIN_STORE_BYTES = 1024


