def select_block(plane):
    """Flat 1-D tile length for the generic kernel: a power of two in
    [32, 1024].  Metadata only (no device-side autotuner: its benchmark path
    calls a non-metadata ATen entry)."""
    block = 32
    while block < plane and block < 1024:
        block *= 2
    return block


@triton.jit
def upsample_bilinear2d_kernel(
    ptr_o,
    ptr_i,
    OH,
    OW,
    IH,
    IW,
    PLANE,
    reciprocal_scale_h,
    reciprocal_scale_w,
    ALIGN_CORNERS: tl.constexpr,
    BLOCK: tl.constexpr,
):
    # Generic (any output size) bilinear path with align_corners in {False, True}.
    #
    # Every tensor here is one-dimensional: a program owns BLOCK consecutive
    # output pixels of a single (n, c) plane, flattened as idx = oh*OW + ow.
    # The store pointer is therefore always built from a per-lane index tensor
    # (tt.addptr over a tensor of offsets), never from a broadcast scalar, so a
    # degenerate call such as OH == OW == 1 cannot collapse the store into a
    # uniform-address rank-2 write.
    pid = tl.program_id(axis=0)
    nc = tl.program_id(axis=1)

    idx = pid * BLOCK + tl.arange(0, BLOCK)
    m_store = idx < PLANE
    oh = idx // OW
    ow = idx % OW

    # Compute the source coordinates
    if ALIGN_CORNERS:
        # When align_corners is True, map corners to corners
        # real_h = oh * (IH - 1) / (OH - 1) when OH > 1
        real_h = tl.where(
            OH > 1,
            oh.to(tl.float32) * (IH - 1) / (OH - 1),
            tl.zeros_like(oh).to(tl.float32),
        )
        real_w = tl.where(
            OW > 1,
            ow.to(tl.float32) * (IW - 1) / (OW - 1),
            tl.zeros_like(ow).to(tl.float32),
        )
    else:
        # When align_corners is False, use area-based scaling
        # real_h = (oh + 0.5) * scale_h - 0.5
        real_h = (oh.to(tl.float32) + 0.5) * reciprocal_scale_h - 0.5
        real_w = (ow.to(tl.float32) + 0.5) * reciprocal_scale_w - 0.5

    # Clamp to valid range
    real_h = tl.maximum(real_h, 0.0)
    real_w = tl.maximum(real_w, 0.0)

    # Get integer parts (top-left corner of the 2x2 region)
    h0 = real_h.to(tl.int32)
    w0 = real_w.to(tl.int32)

    # Clamp so every load address (including masked-off lanes) stays inside the
    # input allocation; the input base stays far below int32 range for the
    # shapes this operator is called with.
    h0 = tl.minimum(h0, IH - 1)
    w0 = tl.minimum(w0, IW - 1)
    h1 = tl.minimum(h0 + 1, IH - 1)
    w1 = tl.minimum(w0 + 1, IW - 1)

    # Compute interpolation weights
    h_weight = real_h - h0.to(tl.float32)
    w_weight = real_w - w0.to(tl.float32)

    # Clamp weights to [0, 1]
    h_weight = tl.maximum(tl.minimum(h_weight, 1.0), 0.0)
    w_weight = tl.maximum(tl.minimum(w_weight, 1.0), 0.0)

    # Compute bilinear weights (1-D: both axes live in the same lane vector)
    w00 = (1.0 - h_weight) * (1.0 - w_weight)
    w01 = (1.0 - h_weight) * w_weight
    w10 = h_weight * (1.0 - w_weight)
    w11 = h_weight * w_weight

    # Neighbor offsets inside one (n, c) input plane
    base_i = nc * IH * IW
    off_00 = base_i + h0 * IW + w0
    off_01 = base_i + h0 * IW + w1
    off_10 = base_i + h1 * IW + w0
    off_11 = base_i + h1 * IW + w1

    data_00 = tl.load(ptr_i + off_00).to(tl.float32)
    data_01 = tl.load(ptr_i + off_01).to(tl.float32)
    data_10 = tl.load(ptr_i + off_10).to(tl.float32)
    data_11 = tl.load(ptr_i + off_11).to(tl.float32)

    result = (
        data_00 * w00
        + data_01 * w01
        + data_10 * w10
        + data_11 * w11
    )

    # Per-lane output index (plane-major), masked for the tail of the plane.
    # Explicit cast so the store operand type always matches the pointer type.
    out_idx = nc * PLANE + idx
    tl.store(ptr_o + out_idx, result.to(ptr_o.dtype.element_ty), mask=m_store)


@triton.jit
def _pack_f16_pair(lo, hi):
    """Pack two f16 lanes into one 32-bit word: lo in bits 0..15, hi in 16..31.

    On a little-endian device this is byte-identical to writing lo at even
    output columns and hi at odd output columns, so it replaces the pairwise
    interleave without any data movement.  Pure bit manipulation, no rounding.
    """
    lo_bits = lo.to(tl.uint16, bitcast=True).to(tl.uint32)
    hi_bits = hi.to(tl.uint16, bitcast=True).to(tl.uint32)
    return (lo_bits | (hi_bits << 16)).to(tl.int32, bitcast=True)


@triton.jit
def upsample_bilinear2d_2x_kernel(
    ptr_o,
    ptr_i,
    IH,
    IW,
    OH,
    OW,
    BLOCK_I: tl.constexpr,
    BLOCK_J: tl.constexpr,
    PACK16: tl.constexpr,
):
    # Exact-2x bilinear upsampling with align_corners=False, row-tiled.
    #
    # For scale exactly 2 the pixel-centre mapping degenerates to fixed weights:
    #   output row 2*i     = 0.25 * in[i-1] + 0.75 * in[i]
    #   output row 2*i + 1 = 0.75 * in[i]   + 0.25 * in[i+1]
    # and the same pair of weights applies along the width, so every input
    # element of the (i-1, i, i+1) x (j-1, j, j+1) stencil is reached with an
    # affine, contiguous address.
    #
    # Memory-organisation form (performance): one program owns BLOCK_I input
    # rows x BLOCK_J input columns, so each of the nine stencil accesses is one
    # 2-D tile transfer (row stride IW, contiguous in the column direction)
    # instead of a separate 256-byte row load, and the total program count
    # drops by BLOCK_I.  Column/row edges are excluded by the load mask and
    # restored with a register select, keeping the offsets affine.  The two
    # interleaved output columns produced by one input column are written as
    # one contiguous 2*BLOCK_J run via tl.interleave, so an output row is a
    # single contiguous store.
    pid_j = tl.program_id(axis=0)
    pid_i = tl.program_id(axis=1)
    nc = tl.program_id(axis=2)

    ii = pid_i * BLOCK_I + tl.arange(0, BLOCK_I)  # input rows of this tile
    j = pid_j * BLOCK_J + tl.arange(0, BLOCK_J)  # input columns of this tile

    # Valid input rows/columns for this program (tail lanes stay inactive;
    # their loads and stores are masked off below).
    row_ok = ii < IH
    in_col = j < IW
    has_l = (j - 1) >= 0
    has_r = (j + 1) < IW

    im = tl.maximum(ii - 1, 0)
    ip = tl.minimum(ii + 1, IH - 1)

    base_i = nc.to(tl.int64) * IH * IW
    off_m = base_i + im[:, None] * IW
    off_c = base_i + ii[:, None] * IW
    off_p = base_i + ip[:, None] * IW

    m_c = row_ok[:, None] & in_col[None, :]
    m_l = m_c & has_l[None, :]
    m_r = m_c & has_r[None, :]
    jl = (j - 1)[None, :]
    jc = j[None, :]
    jr = (j + 1)[None, :]

    ml = tl.load(ptr_i + off_m + jl, mask=m_l, other=0.0).to(tl.float32)
    mc = tl.load(ptr_i + off_m + jc, mask=m_c, other=0.0).to(tl.float32)
    mr = tl.load(ptr_i + off_m + jr, mask=m_r, other=0.0).to(tl.float32)
    cl = tl.load(ptr_i + off_c + jl, mask=m_l, other=0.0).to(tl.float32)
    cc = tl.load(ptr_i + off_c + jc, mask=m_c, other=0.0).to(tl.float32)
    cr = tl.load(ptr_i + off_c + jr, mask=m_r, other=0.0).to(tl.float32)

    # Clamped replication at the row/column borders, matching the previous
    # clamped-index loads.
    ml = tl.where(has_l[None, :], ml, mc)
    mr = tl.where(has_r[None, :], mr, mc)
    cl = tl.where(has_l[None, :], cl, cc)
    cr = tl.where(has_r[None, :], cr, cc)

    # Vertical half of the separable interpolation: output row 2*i blends rows
    # (i-1, i) with weights (0.25, 0.75), output row 2*i+1 blends rows
    # (i, i+1) with weights (0.75, 0.25).
    e_l = 0.25 * ml + 0.75 * cl
    e_c = 0.25 * mc + 0.75 * cc
    e_r = 0.25 * mr + 0.75 * cr

    if PACK16:
        # Output buffer is addressed as 32-bit words; one word holds the two
        # adjacent f16 values (even column, odd column) of this input column.
        out_dtype = ptr_i.dtype.element_ty
        w_col = pid_j * BLOCK_J + tl.arange(0, BLOCK_J)
        w_even_row = nc.to(tl.int64) * OH * OW // 2 + ii.to(tl.int64) * OW
        w_odd_row = w_even_row + OW // 2
        m_out = row_ok[:, None] & (w_col < (OW // 2))[None, :]
    else:
        out_dtype = ptr_o.dtype.element_ty
        out_col = (2 * pid_j) * BLOCK_J + tl.arange(0, 2 * BLOCK_J)
        out_even_row = nc.to(tl.int64) * OH * OW + (2 * ii) * OW
        out_odd_row = out_even_row + OW
        m_out = row_ok[:, None] & (out_col < OW)[None, :]

    # Horizontal half: output column 2*j takes (0.25, 0.75) on columns
    # (j-1, j), output column 2*j+1 takes (0.75, 0.25) on columns (j, j+1).
    # The two values per input column are written as one word (bit-packed)
    # for 16-bit dtypes, otherwise interleaved into one contiguous run.
    ev = (0.25 * e_l + 0.75 * e_c).to(out_dtype)
    od = (0.75 * e_c + 0.25 * e_r).to(out_dtype)
    if PACK16:
        tl.store(
            ptr_o + w_even_row[:, None] + w_col[None, :],
            _pack_f16_pair(ev, od),
            mask=m_out,
        )
    else:
        tl.store(
            ptr_o + out_even_row[:, None] + out_col[None, :],
            tl.interleave(ev, od),
            mask=m_out,
        )

    pl = tl.load(ptr_i + off_p + jl, mask=m_l, other=0.0).to(tl.float32)
    pc = tl.load(ptr_i + off_p + jc, mask=m_c, other=0.0).to(tl.float32)
    pr = tl.load(ptr_i + off_p + jr, mask=m_r, other=0.0).to(tl.float32)
    pl = tl.where(has_l[None, :], pl, pc)
    pr = tl.where(has_r[None, :], pr, pc)

    o_l = 0.75 * cl + 0.25 * pl
    o_c = 0.75 * cc + 0.25 * pc
    o_r = 0.75 * cr + 0.25 * pr

    ev2 = (0.25 * o_l + 0.75 * o_c).to(out_dtype)
    od2 = (0.75 * o_c + 0.25 * o_r).to(out_dtype)
    if PACK16:
        tl.store(
            ptr_o + w_odd_row[:, None] + w_col[None, :],
            _pack_f16_pair(ev2, od2),
            mask=m_out,
        )
    else:
        tl.store(
            ptr_o + out_odd_row[:, None] + out_col[None, :],
            tl.interleave(ev2, od2),
            mask=m_out,
        )


def _pow2_ceil(n):
    p = 1
    while p < n:
        p *= 2
    return p


def select_2x_tile(ih, iw, planes):
    """(BLOCK_I, BLOCK_J) tile for the exact-2x kernel: metadata only.

    BLOCK_J is the smallest power of two covering one input row, capped at 128
    to bound UB usage; BLOCK_I is the largest of 16/8/4/2/1 that still leaves at
    least ~192 programs so the device stays filled on small inputs.  A block
    covers BLOCK_I rows x 2*BLOCK_J output columns, i.e. large enough transfers
    to amortise the per-program cost while keeping enough parallelism.
    """
    block_j = max(1, min(128, _pow2_ceil(iw)))
    block_i = max(1, min(16, _pow2_ceil(ih)))
    col_blocks = (iw + block_j - 1) // block_j
    min_programs = 192
    while block_i > 1:
        row_blocks = (ih + block_i - 1) // block_i
        if row_blocks * col_blocks * planes >= min_programs:
            break
        block_i //= 2
    return block_i, block_j


def bilinear_reciprocal_scale(src_size, dst_size, align_corners, scale):
    if align_corners:
        if dst_size > 1:
            return (src_size - 1) / (dst_size - 1)
        else:
            return 0.0
    else:
        if scale is not None and scale > 0:
            return 1.0 / scale
        else:
            return src_size / dst_size


def _upsample_bilinear2d(
    input: torch.Tensor,
    output_size: Tuple[int],
    align_corners: bool = False,
    scales_h: Optional[float] = None,
    scales_w: Optional[float] = None,
) -> torch.Tensor:
    assert input.device.type in ("npu", "privateuseone")
    assert input.ndim == 4, "The ndim of input must be 4"
    assert len(output_size) == 2, "The len of output_size must be 2"

    OH, OW = output_size
    N, C, IH, IW = input.shape

    reciprocal_scale_h = bilinear_reciprocal_scale(IH, OH, align_corners, scales_h)
    reciprocal_scale_w = bilinear_reciprocal_scale(IW, OW, align_corners, scales_w)

    # Exact-2x fast path: with scale == 2 and align_corners == False the
    # bilinear weights are the constants 0.25/0.75 on both axes, so the kernel
    # needs no data-dependent input address at all.  Selection uses only the
    # runtime metadata of the call (shapes, align_corners, effective scale).
    use_exact_2x = (
        (not align_corners)
        and OH == 2 * IH
        and OW == 2 * IW
        and reciprocal_scale_h == 0.5
        and reciprocal_scale_w == 0.5
    )
    if use_exact_2x:
        block_i, block_j = select_2x_tile(IH, IW, N * C)
        # For f16 the kernel writes bit-packed word pairs (metadata only: the
        # returned tensor aliases the same freshly allocated storage).
        pack16 = input.dtype == torch.float16
        if pack16:
            out_words = torch.empty(
                (N, C, OH, OW // 2), device=input.device, dtype=torch.int32
            )
            output = out_words.view(input.dtype)
            out_arg = out_words
        else:
            output = torch.empty(
                (N, C, OH, OW), device=input.device, dtype=input.dtype
            )
            out_arg = output
        with device_context(input.device):
            upsample_bilinear2d_2x_kernel[
                (triton.cdiv(IW, block_j), triton.cdiv(IH, block_i), N * C)
            ](
                out_arg,
                input,
                IH,
                IW,
                OH,
                OW,
                block_i,
                block_j,
                pack16,
            )
        return output

    # Allocate output
    output = torch.empty((N, C, OH, OW), device=input.device, dtype=input.dtype)

    plane = OH * OW
    block = select_block(plane)
    grid = (triton.cdiv(plane, block), N * C)

    with device_context(input.device):
        upsample_bilinear2d_kernel[grid](
            output,
            input,
            OH,
            OW,
            IH,
            IW,
            plane,
            reciprocal_scale_h,
            reciprocal_scale_w,
            align_corners,
            block,
        )
    return output


